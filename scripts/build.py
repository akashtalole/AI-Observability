def build_scenarios() -> None:
    out = ROOT / "use-cases" / "_generated"
    out.mkdir(exist_ok=True)
    for uc in sorted({s["use_case"] for s in SCENARIOS}):
        rows = ["<!-- GENERATED by scripts/build.py from data/scenarios.json. Edit the JSON. -->", "",
                "Run with `--cycle 240` to alternate healthy phases and these faults, or pin one with `--scenario NAME`. "
                "The alerts listed are the ones each fault is designed to trigger; thresholds are calibrated to the demo traffic.", ""]
        for s in (x for x in SCENARIOS if x["use_case"] == uc):
            rows += [f"### `{s['name']}`: {s['title']}", "", f"**What changes:** {s['injected']}", "", "**What you see**", ""]
            rows += [f"- {x}" for x in s["symptoms"]]
            rows += ["", "**Alerts:** " + ", ".join(f"`{a}`" for a in s["alerts"]) + f" · [runbook]({RUNBOOK_URL}{s['runbook']})", "", "**Investigate**", ""]
            rows += [f"- {x}" for x in s["investigate"]] + [""]
        (out / f"scenarios-{uc}.md").write_text("\n".join(rows), encoding="utf-8")


