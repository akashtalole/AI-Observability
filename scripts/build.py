def esc_cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def build_catalog() -> None:
    groups: "OrderedDict[str, list[dict]]" = OrderedDict((c, []) for c in CATEGORY_ORDER)
    for t in TOOLS:
        groups.setdefault(t["category"], []).append(t)
    lines = [
        "# Tool catalog",
        "",
        "<!-- GENERATED by scripts/build.py from data/tools.json. Edit the JSON, not this file. -->",
        "",
        f"{len(TOOLS)} tools across {sum(1 for g in groups.values() if g)} categories. "
        "Snapshot: October 2026 — **licenses, ownership and features change; verify before adopting.** "
        "Use the [interactive explorer](../artifacts/landscape-explorer.html) to filter.",
        "",
        "`OTel` = ingests/emits OpenTelemetry (Yes / Partial / N/A).",
        "",
    ]
    for cat, items in groups.items():
        if not items:
            continue
        lines += [f"## {cat}", "", "| Tool | Model | License | What it does | Strengths | Watch-outs | OTel |", "|---|---|---|---|---|---|---|"]
        for t in items:
            name = f"[{t['name']}]({t['url']})" if t.get("url") else t["name"]
            lines.append(
                "| " + " | ".join([name, esc_cell(t["model"]), esc_cell(t["license"]), esc_cell(t["description"]),
                                    esc_cell(t["strengths"]), esc_cell(t.get("caveat") or "—"), t.get("otel", "")]) + " |"
            )
        lines.append("")
    (DOCS / "landscape" / "catalog.md").write_text("\n".join(lines), encoding="utf-8")


