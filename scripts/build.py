def build_handbook() -> None:
    pages = nav_pages()
    mdx = markdown.Markdown(
        extensions=["admonition", "attr_list", "md_in_html", "tables", "toc", "pymdownx.details", "pymdownx.superfences",
                    "pymdownx.tabbed", "pymdownx.tasklist", "pymdownx.highlight", "pymdownx.snippets"],
        extension_configs={
            "pymdownx.superfences": {"custom_fences": [{"name": "mermaid", "class": "mermaid",
                                                        "format": __import__("pymdownx.superfences", fromlist=["x"]).fence_code_format}]},
            "pymdownx.highlight": {"use_pygments": False},
            "pymdownx.tabbed": {"alternate_style": True},
            "pymdownx.snippets": {"base_path": [str(ROOT)], "check_paths": True},
            "toc": {"permalink": False},
        },
    )
    sections, toc = [], []
    for page in pages:
        src = (DOCS / page).read_text(encoding="utf-8")
        title_m = re.search(r"^#\s+(.+)$", src, flags=re.M)
        title = title_m.group(1).strip() if title_m else page
        mdx.reset()
        body = mdx.convert(src)

        def fix(m: re.Match) -> str:
            target, frag = m.group(1), m.group(2) or ""
            resolved = posixpath.normpath(posixpath.join(posixpath.dirname(page), target))
            return f'href="#{slug(resolved)}"' if resolved in pages else m.group(0)

        body = re.sub(r'href="([^"#]+\.md)(#[^"]*)?"', fix, body)
        # .html artifact links from inside the handbook (same folder as handbook.html)
        body = re.sub(r'href="(?:\.\./)*artifacts/([^"/]+\.html)"', r'href="\1"', body)
        sections.append(f'<section class="page" id="{slug(page)}">{body}</section>')
        toc.append(f'<a href="#{slug(page)}">{html.escape(title)}</a>')
    out = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Enterprise AI Observability Handbook</title><style>{HANDBOOK_CSS}</style></head>
<body><nav><h2>Contents</h2>{''.join(toc)}</nav><main>
<p><em>Single-file edition generated from the Markdown sources. Diagrams render when online (Mermaid loads from a CDN); offline you see their source.</em></p>
{''.join(sections)}</main>
<script type="module">
import mermaid from "https://cdn.jsdelivr.net/npm/mermaid@11.4.1/dist/mermaid.esm.min.mjs";
mermaid.initialize({{startOnLoad:true,theme:matchMedia("(prefers-color-scheme: dark)").matches?"dark":"default"}});
</script></body></html>"""
    (DOCS / "artifacts" / "handbook.html").write_text(out, encoding="utf-8")


