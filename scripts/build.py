def nav_pages() -> list[str]:
    """Markdown pages in mkdocs.yml nav order (index.md first)."""
    text = (ROOT / "mkdocs.yml").read_text(encoding="utf-8")
    nav = text.split("\nnav:", 1)[1]
    return re.findall(r":\s+(\S+\.md)\s*$", nav, flags=re.M)


def slug(page: str) -> str:
    return "p-" + re.sub(r"[^a-z0-9]+", "-", page[:-3].lower()).strip("-")


